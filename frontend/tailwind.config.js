import { existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import plugin from 'tailwindcss/plugin'

// The design system is WorkChord's DESIGN.md. Its frontmatter tokens live in
// workchord-tokens.json (regenerate with scripts/design-tokens.mjs); values
// that DESIGN.md states only in prose live in workchord-prose.json.
// Next to this file, or under the working directory when a test runner rewrites module URLs.
const themeFile = (name) =>
  [fileURLToPath(new URL(`./src/theme/${name}`, import.meta.url)), join(process.cwd(), 'src', 'theme', name)].find(
    (path) => existsSync(path),
  )
const read = (name) => JSON.parse(readFileSync(themeFile(name), 'utf8'))
const tokens = read('workchord-tokens.json')
const prose = read('workchord-prose.json')
// The dark theme: each token's value in WorkChord's dark theme (regenerate with scripts/dark-tokens.mjs).
const dark = read('workchord-dark.json')
// The figure layer (DESIGN.md, Figures): generated by scripts/figure-colours.mjs.
const figures = read('agdash-figures.json')
const channels = (value) => value.replace(/^rgb\((\d+) (\d+) (\d+)\)$/, '$1 $2 $3')
const figureVariables = (mode) => ({
  ...Object.fromEntries(
    Object.entries(figures.ink[mode].steps).map(([step, value]) => [`--figure-${step}`, channels(value)]),
  ),
  ...Object.fromEntries(Object.entries(figures.roles).map(([role, step]) => [`--figure-${role}`, `var(--figure-${step})`])),
})
// Figure colours are CSS variables, so a theme changes them in one place.
const figureColours = Object.fromEntries(
  [...Object.keys(figures.ink.light.steps), ...Object.keys(figures.roles)].map((name) => [
    `figure-${name}`,
    `rgb(var(--figure-${name}) / <alpha-value>)`,
  ]),
)

// Every token is a CSS variable holding its channels, so a theme changes it in one place
// and opacity modifiers work: "rgb(37 99 235)" is used as "rgb(var(--color-planning-thread) / <alpha-value>)".
const colors = Object.fromEntries(
  Object.keys(tokens.colors).map((name) => [name, `rgb(var(--color-${name}) / <alpha-value>)`]),
)
const themeVariables = (mode) => ({
  // Form controls, scrollbars and the page's own canvas follow the theme too.
  'color-scheme': mode,
  ...Object.fromEntries(
    Object.entries(tokens.colors).map(([name, value]) => [
      `--color-${name}`,
      channels(mode === 'dark' ? dark.colors[name].value : value),
    ]),
  ),
  // WorkChord's dark theme strengthens the shadows and keeps their shapes.
  ...Object.fromEntries(
    Object.keys(dark.shadows).map((name) => [
      `--shadow-${name}`,
      mode === 'dark' ? dark.shadows[name].value : prose.shadows[name],
    ]),
  ),
  ...figureVariables(mode),
})

const typeStep = (style) => [
  style.fontSize,
  {
    lineHeight: String(style.lineHeight),
    fontWeight: String(style.fontWeight),
    ...(style.letterSpacing ? { letterSpacing: style.letterSpacing } : {}),
  },
]

/** @type {import('tailwindcss').Config} */
export default {
  // 7. Hover styles apply only where the device can hover, so a tap never leaves one stuck.
  future: { hoverOnlyWhenSupported: true },
  content: ['./index.html', './src/**/*.{js,ts,jsx,tsx}'],
  // The theme follows the system appearance; data-theme on the root, or on any element,
  // pins one (tests and captures use it). The dark: variant follows the same two.
  darkMode: [
    'variant',
    ['@media (prefers-color-scheme: dark) { &:not([data-theme="light"] *) }', '&:is([data-theme="dark"] *)'],
  ],
  theme: {
    // Only the system's own colours exist, so nothing off-palette can be used by accident.
    colors: {
      transparent: 'transparent',
      current: 'currentColor',
      inherit: 'inherit',
      ...colors,
      // Fixed-opacity roles DESIGN.md names without a value; each is cited in workchord-prose.json.
      ...Object.fromEntries(Object.entries(prose.derived.colors).map(([name, role]) => [name, role.value])),
      ...figureColours,
    },
    screens: {
      // DESIGN.md: gutters shrink at 520px and below; the sidebar becomes a drawer at 1180px and below.
      roomy: `${parseInt(prose.layout.phoneBelow, 10) + 1}px`,
      wide: `${parseInt(prose.layout.drawerBelow, 10) + 1}px`,
    },
    fontFamily: {
      sans: tokens.typography.body.fontFamily.split(',').map((face) => face.trim()),
      mono: ['ui-monospace', 'SFMono-Regular', 'Menlo', 'monospace'],
    },
    borderRadius: { none: '0', ...tokens.rounded, full: '9999px' },
    boxShadow: {
      none: 'none',
      ...Object.fromEntries(Object.keys(dark.shadows).map((name) => [name, `var(--shadow-${name})`])),
    },
    extend: {
      fontSize: {
        ...Object.fromEntries(Object.entries(tokens.typography).map(([name, style]) => [name, typeStep(style)])),
        metadata: [prose.type.metadata, { lineHeight: '1.25' }],
        counter: [prose.type.counter, { lineHeight: '1.25' }],
      },
      spacing: {
        ...tokens.spacing,
        conductor: prose.layout.conductorHeight,
        sidebar: prose.layout.sidebarWidth,
        control: tokens.components['button-primary'].height,
        'control-lg': prose.controls.large,
        'control-sm': prose.controls.small,
        'workspace-item': tokens.components['workspace-active'].height,
        'phone-x': prose.layout.phoneGutterX,
        touch: prose.layout.coarseTarget,
      },
      // Data-heavy workbenches, such as a session's overview and timeline, may reach 1440px.
      maxWidth: { page: prose.layout.pageMaxWidth, workbench: prose.layout.workbenchMaxWidth },
      transitionDuration: { state: prose.derived.stateDuration.value },
      keyframes: {
        // Starts already visible, so a delayed or paused animation never hides the drawer.
        'drawer-in': {
          from: { transform: 'translateX(-16px)', opacity: '0.85' },
          to: { transform: 'translateX(0)', opacity: '1' },
        },
      },
    },
  },
  plugins: [
    // DESIGN.md: coarse-pointer controls get at least 44px targets.
    plugin(({ addVariant }) => addVariant('pointer-coarse', '@media (pointer: coarse)')),
    // The tokens', shadows' and figure layer's values: light by default, dark when the
    // system asks for dark or data-theme says so.
    plugin(({ addBase }) =>
      addBase({
        ':root, [data-theme="light"]': themeVariables('light'),
        '@media (prefers-color-scheme: dark)': { ':root:not([data-theme="light"])': themeVariables('dark') },
        '[data-theme="dark"]': themeVariables('dark'),
      }),
    ),
  ],
}
