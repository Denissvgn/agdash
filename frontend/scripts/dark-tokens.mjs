// Read the dark value of every design token from WorkChord's dark theme.
//
//   node scripts/dark-tokens.mjs <path to WorkChord/frontend>
//
// rewrites src/theme/workchord-dark.json. WorkChord's DESIGN.md states light values
// only; its frontend's stylesheets hold the dark theme, as colour roles. Each token is
// tied here to the role that carries it: the role's light value must equal the token's
// value in DESIGN.md, or the script refuses, so a dark value is never matched by guess.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

// Token in DESIGN.md -> the custom property that carries it in WorkChord's frontend.
export const ROLES = {
  'planning-thread': 'color-action-primary',
  'planning-thread-hover': 'color-action-primary-hover',
  'planning-thread-soft': 'color-action-muted',
  // The conductor bar is one navy in every theme: these two have no dark override.
  'conductor-navy': 'wc-shell',
  'conductor-panel': 'wc-shell-panel',
  'canvas-mist': 'color-surface-canvas',
  'working-paper': 'color-surface-card',
  'primary-ink': 'color-content-primary',
  'secondary-ink': 'color-content-secondary',
  'strong-rule': 'color-border-strong',
  'status-planned': 'color-status-planned-solid',
  'status-active': 'color-status-active-solid',
  'status-resolved': 'color-status-resolved-solid',
  'status-closed': 'color-status-closed-solid',
  'feedback-warning': 'color-feedback-warning',
  'feedback-danger': 'color-feedback-danger',
}

// Shadow in DESIGN.md's prose -> its custom property.
export const SHADOWS = { resting: 'wc-sh-1', raised: 'wc-sh-2', popover: 'wc-sh-pop' }

const SOURCES = ['src/styles/globals.css', 'src/styles/planning-masters.css']
const LIGHT = [':root', ":root, [data-theme='light']"]
const DARK = ["[data-theme='dark']"]

/** The custom properties a stylesheet sets under any of the given selectors, later ones winning. */
export function properties(css, selectors) {
  const found = {}
  const plain = css.replace(/\/\*[\s\S]*?\*\//g, '')
  for (const [, selector, body] of plain.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    // What precedes a rule may end an at-rule line (`@tailwind base;`), not belong to its selector.
    if (!selectors.includes(selector.split(';').pop().trim().replace(/\s+/g, ' '))) continue
    for (const [, name, value] of body.matchAll(/--([\w-]+):\s*([^;]+);/g)) found[name] = value.trim()
  }
  return found
}

// "30 41 59" and "rgb(30 41 59)" are the same colour, written two ways upstream.
const colour = (value) => (/^\d+ \d+ \d+$/.test(value) ? `rgb(${value})` : value)

export function darkTokens(stylesheets, tokens, prose) {
  const light = Object.assign({}, ...stylesheets.map((css) => properties(css, LIGHT)))
  const dark = { ...light, ...Object.assign({}, ...stylesheets.map((css) => properties(css, DARK))) }
  const pair = (name, property, stated) => {
    if (!(property in light)) throw new Error(`WorkChord's stylesheets do not set --${property}`)
    if (colour(light[property]) !== stated) {
      throw new Error(`${name} is ${stated} in DESIGN.md, but --${property} is ${colour(light[property])} in the light theme`)
    }
    return { role: `--${property}`, value: colour(dark[property]) }
  }
  for (const name of Object.keys(tokens.colors)) {
    if (!(name in ROLES)) throw new Error(`no WorkChord colour role is named for ${name}`)
  }
  return {
    source:
      "WorkChord's dark theme: the [data-theme='dark'] values in its frontend's src/styles/globals.css and " +
      'planning-masters.css. Generated by scripts/dark-tokens.mjs; do not edit by hand.',
    colors: Object.fromEntries(
      Object.keys(tokens.colors).map((name) => [name, pair(name, ROLES[name], tokens.colors[name])]),
    ),
    shadows: Object.fromEntries(
      Object.entries(SHADOWS).map(([name, property]) => [name, pair(name, property, prose.shadows[name])]),
    ),
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const frontend = process.argv[2]
  if (!frontend) {
    console.error('usage: node scripts/dark-tokens.mjs <path to WorkChord/frontend>')
    process.exit(2)
  }
  const theme = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'theme')
  const read = (name) => JSON.parse(readFileSync(join(theme, name), 'utf8'))
  const stylesheets = SOURCES.map((path) => readFileSync(join(frontend, path), 'utf8'))
  const target = join(theme, 'workchord-dark.json')
  writeFileSync(
    target,
    JSON.stringify(darkTokens(stylesheets, read('workchord-tokens.json'), read('workchord-prose.json')), null, 2) + '\n',
  )
  console.log(`wrote ${target}`)
}
